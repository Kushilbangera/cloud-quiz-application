drop policy if exists "profiles select own" on public.profiles;
create policy "profiles select own" on public.profiles for select to authenticated using (auth.uid() = id);

drop policy if exists "public education levels read" on public.education_levels;
create policy "public education levels read" on public.education_levels for select using (true);
drop policy if exists "public streams read" on public.streams;
create policy "public streams read" on public.streams for select using (true);
drop policy if exists "public subjects read" on public.subjects;
create policy "public subjects read" on public.subjects for select using (true);
drop policy if exists "public topics read" on public.topics;
create policy "public topics read" on public.topics for select using (true);
drop policy if exists "public quizzes read" on public.quizzes;
create policy "public quizzes read" on public.quizzes for select using (published = true);
drop policy if exists "public questions read" on public.questions;
create policy "public questions read" on public.questions for select using (true);
drop policy if exists "results own read" on public.results;
create policy "results own read" on public.results for select to authenticated using (auth.uid() = user_id);

