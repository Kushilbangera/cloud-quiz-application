create unique index if not exists education_levels_name_uidx on public.education_levels(name);
create unique index if not exists streams_level_name_uidx on public.streams(education_level_id,name);
create unique index if not exists subjects_stream_name_uidx on public.subjects(stream_id,name);
create unique index if not exists topics_subject_name_uidx on public.topics(subject_id,name);

-- Allow admin accounts. Older versions used a user-only constraint.
do $$
declare c record;
begin
  for c in select conname from pg_constraint where conrelid = 'public.profiles'::regclass and contype = 'c' and pg_get_constraintdef(oid) ilike '%role%' loop
    execute format('alter table public.profiles drop constraint if exists %I', c.conname);
  end loop;
exception when undefined_table then null;
end $$;
alter table public.profiles add constraint profiles_role_check check (role in ('user','admin'));

-- Keep profile rows in sync with Supabase Auth.
create or replace function public.handle_new_user_profile()
returns trigger language plpgsql security definer set search_path = public
as $$
begin
  insert into public.profiles (id, email, full_name, role, plan)
  values (new.id, new.email, coalesce(new.raw_user_meta_data ->> 'full_name',''), 'user', 'free')
  on conflict (id) do update set email = excluded.email;
  insert into public.user_plans (email, name, plan)
  values (new.email, coalesce(new.raw_user_meta_data ->> 'full_name',''), 'free')
  on conflict (email) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created_profile on auth.users;
create trigger on_auth_user_created_profile after insert on auth.users for each row execute function public.handle_new_user_profile();

