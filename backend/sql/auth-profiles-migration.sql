-- QuizCloud complete Supabase schema
-- Run this in a fresh Supabase project, or use it as the reference migration for the existing project.

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text not null default '',
  email text unique not null,
  role text not null default 'user' check (role in ('user','admin')),
  plan text not null default 'free' check (plan in ('free','premium')),
  avatar_url text,
  created_at timestamptz not null default now()
);

create table if not exists public.education_levels (
  id bigint generated by default as identity primary key,
  name text not null unique,
  description text,
  created_at timestamptz not null default now()
);

create table if not exists public.streams (
  id bigint generated by default as identity primary key,
  education_level_id bigint not null references public.education_levels(id) on delete cascade,
  name text not null,
  description text,
  created_at timestamptz not null default now(),
  unique (education_level_id, name)
);

create table if not exists public.subjects (
  id bigint generated by default as identity primary key,
  stream_id bigint not null references public.streams(id) on delete cascade,
  name text not null,
  description text,
  created_at timestamptz not null default now(),
  unique (stream_id, name)
);

create table if not exists public.topics (
  id bigint generated by default as identity primary key,
  subject_id bigint not null references public.subjects(id) on delete cascade,
  name text not null,
  description text,
  created_at timestamptz not null default now(),
  unique (subject_id, name)
);

create table if not exists public.quizzes (
  id bigint generated by default as identity primary key,
  title text not null,
  description text default '',
  category text not null,
  difficulty text not null,
  total_questions integer not null default 0,
  time_limit integer not null default 10,
  subject_id bigint references public.subjects(id) on delete set null,
  topic_id bigint references public.topics(id) on delete set null,
  access_type text not null default 'free' check (access_type in ('free','premium')),
  published boolean not null default true,
  premium_features jsonb not null default '{"explanations":false,"hints":false,"negative_marking":false,"advanced_analytics":false,"mock_exam":false,"certificate":false}'::jsonb,
  created_at timestamptz not null default now()
);

create table if not exists public.questions (
  id bigint generated by default as identity primary key,
  quiz_id bigint not null references public.quizzes(id) on delete cascade,
  question_text text not null,
  option_a text not null,
  option_b text not null,
  option_c text not null,
  option_d text not null,
  correct_answer text not null check (upper(correct_answer) in ('A','B','C','D')),
  explanation text default '',
  marks integer not null default 1,
  negative_marks numeric(5,2) not null default 0,
  created_at timestamptz not null default now()
);

create table if not exists public.results (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  quiz_id bigint not null references public.quizzes(id) on delete cascade,
  score integer not null default 0,
  total_questions integer not null,
  percentage numeric(5,2) not null default 0,
  completed_at timestamptz not null default now()
);

create table if not exists public.payments (
  id bigint generated by default as identity primary key,
  order_id text unique not null,
  payment_id text unique,
  email text not null,
  name text not null default '',
  amount integer not null check (amount > 0),
  currency text not null default 'INR',
  status text not null default 'created' check (status in ('created','paid','failed')),
  paid_at timestamptz,
  created_at timestamptz not null default now()
);

create table if not exists public.user_plans (
  email text primary key,
  name text not null default '',
  plan text not null default 'free' check (plan in ('free','premium')),
  razorpay_order_id text,
  updated_at timestamptz not null default now()
);

